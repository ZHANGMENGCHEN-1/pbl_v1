"""Frontend-only teaching companion. Vite on port 5174; no backend or paid model."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect


with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];api_calls=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:api_calls.append(r.url) if '/api/' in r.url else None)
    page.goto('http://127.0.0.1:5174/')
    expect(page.locator('.home-project-card')).to_have_count(3)
    card=page.locator('.home-project-card.teaching')
    expect(card).to_contain_text('教学 Agent')
    Path('test-results').mkdir(exist_ok=True)
    page.screenshot(path='test-results/teaching-agent-home.png',full_page=True)
    card.click()
    expect(page).to_have_url('http://127.0.0.1:5174/projects/teaching-agent')
    expect(page.get_by_role('heading',name='和小知聊一聊')).to_be_visible()
    expect(page.locator('.teaching-demo-banner')).to_contain_text('尚未接入真实 AI')
    expect(page.locator('.robot-stage > .teaching-robot-view')).to_be_visible()
    expect(page.get_by_role('button',name='发送',exact=True)).to_be_disabled()
    expect(page.locator('.teaching-message')).to_have_count(1)
    page.screenshot(path='test-results/teaching-agent-desktop.png',full_page=True)

    page.locator('.starter-prompts button').first.click()
    expect(page.locator('.teaching-message.student')).to_have_count(1)
    expect(page.get_by_role('button',name='暂停回复',exact=True)).to_be_visible()
    expect(page.get_by_role('button',name='发送',exact=True)).to_be_visible(timeout=10000)
    expect(page.locator('.teaching-message.assistant').last).to_contain_text('把任务拆小一点')
    page.reload()
    expect(page.locator('.teaching-message.student')).to_have_count(1)
    expect(page.locator('.teaching-message.assistant')).to_have_count(2)

    page.locator('.topic-button').nth(1).click()
    expect(page.locator('.topic-button').nth(1)).to_have_attribute('aria-pressed','true')
    expect(page.locator('.starter-prompts')).to_contain_text('这一步我没看懂')
    input=page.get_by_role('textbox',name='和小知说说你的问题')
    input.fill('我正在输入中文')
    input.dispatch_event('keydown',{'key':'Enter','code':'Enter','isComposing':True,'bubbles':True})
    expect(page.locator('.teaching-message.student')).to_have_count(1)
    input.press('Shift+Enter')
    assert '\n' in input.input_value()
    input.fill('这一步我没看懂，可以陪我找找原因吗？')
    input.press('Enter')
    expect(page.locator('.teaching-message.student')).to_have_count(2)
    page.get_by_role('button',name='暂停回复',exact=True).click()
    expect(page.get_by_role('button',name='发送',exact=True)).to_be_disabled()
    expect(page.locator('.typing-indicator')).to_have_count(0)

    input.fill('我想再试一下')
    page.get_by_role('button',name='发送',exact=True).click()
    expect(page.get_by_role('button',name='发送',exact=True)).to_be_visible(timeout=10000)
    expect(page.locator('.teaching-message.assistant').last).to_contain_text('卡在哪里')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth')
    input.scroll_into_view_if_needed()
    page.screenshot(path='test-results/teaching-agent-mobile.png',full_page=True)

    page.locator('.chat-restart').click()
    page.locator('.el-message-box').get_by_role('button',name='继续聊',exact=True).click()
    expect(page.locator('.teaching-message.student')).to_have_count(3)
    page.locator('.chat-restart').click()
    page.locator('.el-message-box').get_by_role('button',name='重新开始',exact=True).click()
    expect(page.locator('.teaching-message')).to_have_count(1)
    page.get_by_role('link',name='返回项目首页',exact=True).click()
    expect(page.locator('.home-project-card')).to_have_count(3)
    assert not errors,errors
    assert not api_calls,api_calls
    browser.close()
    print('Teaching Agent passed: homepage entry, route, explicit demo, send/stream/stop, IME and newline, topic changes, local restore, reset confirmation and mobile layout; no backend calls.')
